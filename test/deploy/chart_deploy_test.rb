require "test_helper"

# billing's deploy artifact is a real chart, and its content is the contract
# the substrate's `Application` pulls.
#
# ## Why this file tests the chart and not `config/deploy.yml`
#
# The preserved `test/deploy/deploy_config_test.rb` from the October wave
# asserted Kamal's config — the healthcheck path, `env.secret`, no placeholder
# host — against a `config/deploy.yml` that is still the stock template. That
# test was red the moment it landed, and the reason it was red is the fleet's
# direction rather than billing's: `cafaye/notes/deployment.md` puts the deployment on the
# k3s/Argo substrate and `cafaye/notes/launch.md` is explicit that "no new launch work is
# Kamal work". A Kamal config test would be an investment in a file that
# retires at parity, written for a service that has never deployed.
#
# The deploy artifact for this service is the **chart** — generated by
# `cafe gen chart` from this repository's own `cafaye.yml`, packaged and pushed
# by kit's publish workflow, and pulled by the substrate's `Application`, which
# names `oci://ghcr.io/cafaye/charts` chart `billing` at
# `targetRevision: 0.1.1`. So this file asserts the chart's content and the
# publish loop's seam: the facts that make the loop work, not that files exist.
#
# It reads four files and renders nothing. No database, no boot.
class ChartDeployTest < ActiveSupport::TestCase
  setup do
    @chart = YAML.safe_load_file(Rails.root.join("chart/Chart.yaml"))
    @workflow = File.read(Rails.root.join("ci/publish.yml"))
    @deployment = File.read(Rails.root.join("chart/templates/deployment.yaml"))
    @values = YAML.safe_load_file(Rails.root.join("chart/values.yaml"))
  end

  # --- the seam between the chart and the substrate ---------------------------

  # The two facts the substrate pins, and the two this chart must carry: the
  # `Application` names `chart: billing` and `targetRevision: 0.1.2`. A chart
  # version that moves without the Application moving is a service that never
  # deploys — the OCI tag IS the chart version.
  test "chart name and version are what the substrate's Application pulls" do
    assert_equal "billing", @chart.fetch("name")
    assert_equal "0.1.2", @chart.fetch("version")
  end

  # Readiness, and the fleet's contract: the rollout waits on `/readyz`, which
  # is the probe that answers `SELECT 1`. A gate on `/healthz` accepts a
  # container that cannot reach its database — liveness the substrate would
  # call ready.
  test "the readiness probe reads /readyz" do
    assert_includes @deployment, "/readyz"
    assert_not_includes @deployment, "path: /up", "`/up` is Rails' boot probe, not a readiness one"
  end

  # The chart is INTERNAL: billing is not one of the two exposed services
  # (gateway and parlor are), so the Ingress ships off and the service is
  # reached through the namespace rather than a hostname. A values commit turns
  # it on if that ever changes, which is what the off default is for.
  test "ingress ships off, because billing is an internal service" do
    assert_equal false, @values.dig("ingress", "enabled")
  end

  # The one thing the chart must NOT contain: the substrate owns the
  # `Application`, and a second one named `billing` in `argocd` fighting the
  # substrate's is split brain. The generator stopped emitting it in m88; this
  # is the assertion that keeps a regenerated chart from growing one back.
  test "the chart carries no application.yaml, because kit owns it" do
    refute File.exist?(Rails.root.join("chart/templates/application.yaml"))
  end

  # --- the publish loop, and the caller that is kit's --------------------------

  # Every absence assertion above is paired with a presence one: a chart with
  # no deployment template at all passes "no application.yaml", so the workload
  # the substrate would run is asserted to exist.
  test "the chart carries the workload the substrate runs" do
    assert_includes @deployment, "kind: Deployment"
    assert_includes @deployment, "image:"
    assert_includes @values.dig("image", "repository"), "ghcr.io/cafaye/billing"
    # A floating tag is a deploy that changes when somebody else pushes.
    refute_equal "latest", @values.dig("image", "tag")
  end

  # One composition, and it is kit's: a caller that inlines the steps has
  # forked it, and the fork is the drift kit exists to prevent.
  test "the publish caller is kit's composed workflow, and nothing inlined" do
    assert_includes @workflow, "uses: cafaye/kit/ci/publish.reusable.yml@master"
    refute_includes @workflow, "helm package", "the composition is kit's; a caller that packages has forked it"
  end

  # A reusable workflow can request a permission but cannot grant itself one.
  # A caller that omits the grant gets a 401 at the push that reads like a
  # wrong password.
  test "the publish caller grants packages: write" do
    assert_includes @workflow, "packages: write"
  end

  # The reusable workflows default to `push: false`, so a caller that omits
  # the input publishes nothing and says nothing.
  test "the publish caller opts in with push: true" do
    assert_includes @workflow, "push: true"
  end
end
